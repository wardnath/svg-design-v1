// Rasterizes Natural Earth 110m land (world-atlas) into a coarse dot grid for the
// threat-map widgets. Output: src/design-kit/worldmask.js (bit-packed rows).
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const topo = require('topojson-client');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const land = require(path.join(root, 'node_modules/world-atlas/land-110m.json'));
const geo = topo.feature(land, land.objects.land);
const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === 'Polygon') polys.push(g.coordinates);
  else if (g.type === 'MultiPolygon') for (const p of g.coordinates) polys.push(p);
}
const inRing = (x, y, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const isLand = (lon, lat) => polys.some(p => inRing(lon, lat, p[0]) && !p.slice(1).some(h => inRing(lon, lat, h)));
const COLS = 132, ROWS = 58, LAT0 = 82, LAT1 = -56;
const rows = [];
let n = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = LAT0 + (LAT1 - LAT0) * (r + 0.5) / ROWS;
  let bits = '';
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + 360 * (c + 0.5) / COLS;
    const b = isLand(lon, lat) ? 1 : 0; n += b;
    bits += b;
  }
  const padded = bits.padEnd(Math.ceil(COLS / 4) * 4, '0');
  let hex = '';
  for (let i = 0; i < padded.length; i += 4) hex += parseInt(padded.slice(i, i + 4), 2).toString(16);
  rows.push(hex);
}
const js = `// Generated by scripts/make-worldmask.mjs from world-atlas land-110m (Natural Earth, public domain).\n` +
  `// ${COLS}×${ROWS} cells, equirectangular, latitude ${LAT0}° to ${LAT1}°. One hex string per row, 1 = land.\n` +
  `export const COLS = ${COLS}, ROWS = ${ROWS}, LAT0 = ${LAT0}, LAT1 = ${LAT1};\nexport const ROWS_HEX = ${JSON.stringify(rows)};\n` +
  `export function landAt(c, r) { const h = ROWS_HEX[r]; if (!h) return false; const nib = parseInt(h[c >> 2], 16); return ((nib >> (3 - (c & 3))) & 1) === 1; }\n` +
  `export function project(lon, lat) { return [((lon + 180) / 360) * COLS, ((LAT0 - lat) / (LAT0 - LAT1)) * ROWS]; }\n`;
fs.writeFileSync(path.join(root, 'src/design-kit/worldmask.js'), js);
console.log('land cells', n, 'of', COLS * ROWS);
for (let r = 0; r < ROWS; r += 2) console.log(rows[r].split('').map(h => parseInt(h, 16).toString(2).padStart(4, '0')).join('').replace(/0/g, ' ').replace(/1/g, '#'));
