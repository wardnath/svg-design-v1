// Extracts glyph outlines + advances + kerning from Inter and JetBrains Mono (OFL-1.1)
// into src/design-kit/glyphs.js, so design SVGs can be exported with outlined text,
// the way Figma exports text by default.
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const fsrc = (pkg, file) => path.join(root, 'node_modules/@fontsource', pkg, 'files', file);

const FONTS = {
  'inter-400': fsrc('inter', 'inter-latin-400-normal.woff'),
  'inter-500': fsrc('inter', 'inter-latin-500-normal.woff'),
  'inter-600': fsrc('inter', 'inter-latin-600-normal.woff'),
  'inter-700': fsrc('inter', 'inter-latin-700-normal.woff'),
  'mono-400': fsrc('jetbrains-mono', 'jetbrains-mono-latin-400-normal.woff'),
  'mono-500': fsrc('jetbrains-mono', 'jetbrains-mono-latin-500-normal.woff'),
  'mono-600': fsrc('jetbrains-mono', 'jetbrains-mono-latin-600-normal.woff'),
};
let chars = '';
for (let c = 32; c < 127; c++) chars += String.fromCharCode(c);
chars += '·•—–’‘“”…×±©®™€£°−↑↓→←▲▼●✓';

const out = {};
for (const [key, file] of Object.entries(FONTS)) {
  const buf = fs.readFileSync(file);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const os2 = font.tables.os2, hhea = font.tables.hhea;
  const glyphs = {};
  const have = [];
  for (const ch of chars) {
    const g = font.charToGlyph(ch);
    if (!g || (g.index === 0 && ch !== ' ')) continue;
    have.push(ch);
    // relative path commands in font units, y up
    let d = '', cx = 0, cy = 0;
    const r = v => Math.round(v);
    for (const c of g.path.commands) {
      if (c.type === 'M') { d += `m${r(c.x - cx)} ${r(c.y - cy)}`; cx = r(c.x); cy = r(c.y); }
      else if (c.type === 'L') { d += `l${r(c.x - cx)} ${r(c.y - cy)}`; cx = r(c.x); cy = r(c.y); }
      else if (c.type === 'Q') { d += `q${r(c.x1 - cx)} ${r(c.y1 - cy)} ${r(c.x - cx)} ${r(c.y - cy)}`; cx = r(c.x); cy = r(c.y); }
      else if (c.type === 'C') { d += `c${r(c.x1 - cx)} ${r(c.y1 - cy)} ${r(c.x2 - cx)} ${r(c.y2 - cy)} ${r(c.x - cx)} ${r(c.y - cy)}`; cx = r(c.x); cy = r(c.y); }
      else if (c.type === 'Z') d += 'z';
    }
    glyphs[ch] = [Math.round(g.advanceWidth), d.replace(/ -/g, '-')];
  }
  const kern = {};
  let nk = 0;
  for (const a of have) for (const b of have) {
    const v = font.getKerningValue(font.charToGlyph(a), font.charToGlyph(b));
    if (v) { kern[a + b] = Math.round(v); nk++; }
  }
  out[key] = {
    upm: font.unitsPerEm,
    asc: hhea.ascender, desc: hhea.descender, lineGap: hhea.lineGap,
    typoAsc: os2.sTypoAscender, typoDesc: os2.sTypoDescender, capH: os2.sCapHeight, xH: os2.sxHeight,
    glyphs, kern,
  };
  console.log(key, 'upm', font.unitsPerEm, 'glyphs', have.length, 'kern pairs', nk, 'missing', [...chars].filter(c => !have.includes(c)).join(''));
}
const js = '// Generated by scripts/extract-glyphs.mjs from @fontsource/inter and @fontsource/jetbrains-mono (SIL OFL 1.1).\n' +
  '// Glyph outlines are relative path commands in font units (y up).\nexport default ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'src/design-kit/glyphs.js'), js);
console.log('wrote glyphs.js', (js.length / 1024).toFixed(1), 'KB');
